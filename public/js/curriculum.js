/* ============================================================
   索引与查询
   ============================================================ */
export const POINT_BY_ID = Object.fromEntries(POINTS.map((p) => [p.id, p]));

export const MODULES = [...new Set(POINTS.map((p) => p.module))];

export function pointById(id) {
  return POINT_BY_ID[id] || null;
}

/** 按名字/id 模糊找一个考点。模型给的名字往往不精确（「罗尔定理」vs「rolle」）。 */
export function findPoint(query) {
  const q = String(query || '').trim();
  if (!q) return null;
  const lower = q.toLowerCase();
  const exact = POINTS.find((p) => p.id === lower || p.name === q);
  if (exact) return exact;
  // 包含式匹配：先看名字里含查询，再看查询里含名字
  const nameHit = POINTS.find((p) => p.name.includes(q) || q.includes(p.name));
  if (nameHit) return nameHit;
  return POINTS.find((p) => p.id.includes(lower) || p.chapter.includes(q)) || null;
}

/* ============================================================
   ★ 按角色裁剪资料 —— 「结构性无知」的实现处
   ============================================================
   注意：这个函数是**唯一的**资料出口。任何工具想拿考点内容都得走它。
   如果某个工具绕过去直接读 POINT_BY_ID，角色的信息差就失效了，
   四个 agent 会立刻收敛成同一种腔调。
   ============================================================ */
export function materialFor(point, depthKey) {
  if (!point) return null;
  const d = DEPTH[depthKey] || DEPTH.c;
  const out = { id: point.id, name: point.name, module: point.module, chapter: point.chapter };

  if (d.definition === 'full') out.definition = point.definition;
  else if (d.definition === 'first') out.definition = firstSentence(point.definition);

  if (d.intuition) out.intuition = point.intuition;
  if (d.scope) out.scope = point.scope;
  if (d.example) out.example = point.example;
  if (d.examForm) out.examForm = point.examForm;

  if (d.related) {
    out.related = (point.related || []).map((id) => {
      const r = POINT_BY_ID[id];
      return r ? { id: r.id, name: r.name } : null;
    }).filter(Boolean);
  }
  if (d.mistakes) {
    // 老师能看到「这个考点学生常错在哪」，学生看不到
    out.commonMistakes = (point.questions || [])
      .flatMap((q) => q.distractors || [])
      .map((d2) => ({ text: d2.text, why: d2.why }));
  }
  return out;
}

/** 这个角色能看到的字段名（用于自检与 UI 展示）。 */
export function visibleFields(depthKey) {
  const d = DEPTH[depthKey] || DEPTH.c;
  return Object.keys(d).filter((k) => d[k]);
}

/** 取某个考点的第 i 个干扰项。角色一人分一个，不够才复用（用 min 夹住，别越界）。 */
export function distractorAt(point, i) {
  const list = (point && point.questions || []).flatMap((q) => q.distractors || []);
  if (!list.length) return null;
  const idx = Math.min(Math.max(0, Number(i) || 0), list.length - 1);
  return { ...list[idx], total: list.length, index: idx };
}
