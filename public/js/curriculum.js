/* 取定义的第一句。中文句读里 。；！？ 都算句末，换行也算。
 * 切不出来（没有句号）就整句返回——宁可给多一点，也别给空字符串。 */
export function firstSentence(text) {
  const s = String(text || '').trim();
  if (!s) return '';
  const m = s.match(/^[\s\S]*?[。；！？]/);
  return m ? m[0] : s;
}

